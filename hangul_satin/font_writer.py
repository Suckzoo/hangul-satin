"""Write an InkStitch lettering font folder: font.json, ltr.svg (or ltr/*.svg) and report.json."""
import json
from dataclasses import dataclass, field
from pathlib import Path
from xml.sax.saxutils import quoteattr

from fontTools.ttLib import TTFont

from .compose import compose_glyph
from .inkstitch_bridge import PX_PER_MM, glyph_report, satin_attributes
from .outline import glyph_outline

EM_WIDTH = 1300
EM_HEIGHT = 1300
WORD_SPACE_EM = 300
LINE_HEIGHT_EM = 1200
LARGE_FONT_BATCH = 500
THREAD_COLOR = "#1f4e79"
SVG_HEAD = ('<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" '
            'xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" '
            'xmlns:sodipodi="http://sodipodi.sourceforge.net/DTD/sodipodi-0.dtd" '
            'xmlns:inkstitch="http://inkstitch.org/namespace" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><metadata>'
            '<inkstitch:min_stitch_len_mm>0.1</inkstitch:min_stitch_len_mm>'
            '<inkstitch:collapse_len_mm>3.0</inkstitch:collapse_len_mm>'
            '<inkstitch:inkstitch_svg_version>3</inkstitch:inkstitch_svg_version></metadata>')


@dataclass
class FontBuildResult:
    built: list[str] = field(default_factory=list)
    failed: dict[str, list[str]] = field(default_factory=dict)
    review: dict[str, list[str]] = field(default_factory=dict)


def write_font(font_path: Path, chars: str, output_dir: Path, size_mm: float, batch_size: int | None = None, check: bool = False) -> FontBuildResult:
    """Build every character it can. A failed character goes in the report and does not stop the build."""
    font = TTFont(font_path)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    scale = size_mm / 1000 * PX_PER_MM
    result, layers, advances = FontBuildResult(), [], {}
    for char in dict.fromkeys(chars):
        if char.isspace():
            continue
        layer, advance = _build_glyph(font, char, size_mm, scale, result, check)
        if layer:
            layers.append(layer)
            advances[char] = round(advance * scale, 2)
            result.built.append(char)
    _write_layers(output_dir, layers, scale, batch_size)
    _write_metadata(output_dir, font, result.built, advances, size_mm, scale)
    report = dict(built=result.built, failed=result.failed, review=result.review)
    (output_dir / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf8")
    return result


def _build_glyph(font, char, size_mm, scale, result, check):
    outline = glyph_outline(font, char)
    if outline is None:
        result.failed[char] = ["missing"]
        return None, 0
    try:
        strokes = compose_glyph(outline)
        if not strokes:
            result.failed[char] = ["no strokes"]
            return None, 0
        layer = _glyph_layer(char, strokes, size_mm, scale)
        if check:
            reasons = glyph_report(outline, size_mm).reasons
            if reasons:
                result.review[char] = reasons
    except Exception as error:  # one bad glyph must not stop a font of thousands
        result.failed[char] = [f"error: {error}"]
        return None, 0
    return layer, outline.advance


def _glyph_layer(char, strokes, size_mm, scale):
    label = quoteattr(f"GlyphLayer-{char}")
    parts = [f'<g inkscape:groupmode="layer" inkscape:label={label} id="glyph-{ord(char):x}">']
    for index, stroke in enumerate(strokes):
        attrs = " ".join(f'inkstitch:{name}="{value}"' for name, value in satin_attributes(stroke, size_mm).items())
        parts.append(f'<path id="glyph-{ord(char):x}-{index}" inkscape:label="stroke {index}" '
                     f'style="fill:none;stroke:{THREAD_COLOR};stroke-width:1" {attrs} d="{stroke.path_data(scale)}"/>')
    parts.append("</g>")
    return "\n".join(parts)


def _write_layers(output_dir, layers, scale, batch_size):
    head = SVG_HEAD.format(w=round(EM_WIDTH * scale, 2), h=round(EM_HEIGHT * scale, 2))
    size = batch_size or LARGE_FONT_BATCH
    if len(layers) <= size and batch_size is None:
        (output_dir / "ltr.svg").write_text("\n".join([head, *layers, "</svg>"]), encoding="utf8")
        return
    folder = output_dir / "ltr"
    folder.mkdir(exist_ok=True)
    for start in range(0, len(layers), size):
        part = "\n".join([head, *layers[start:start + size], "</svg>"])
        (folder / f"part-{start // size:04d}.svg").write_text(part, encoding="utf8")


def _write_metadata(output_dir, font, built, advances, size_mm, scale):
    name = font["name"].getDebugName(4) or Path(output_dir).name
    meta = dict(name=f"{name} {size_mm:g}mm", description="Generated by hangul-satin", font_license=font["name"].getDebugName(13) or "",
                default_variant="ltr", text_direction="ltr", keywords=["satin"], original_font=name, original_font_url="",
                leading=round(LINE_HEIGHT_EM * scale, 2), auto_satin=False, scale_cross_stitch_pattern=False, reversible=False, sortable=False,
                combine_at_sort_indices=[], letter_case="", default_glyph=built[0] if built else "", size=float(size_mm),
                min_scale=1.0, max_scale=1.0, horiz_adv_x_default=None, horiz_adv_x_space=round(WORD_SPACE_EM * scale, 2),
                units_per_em=round(1000 * scale, 2), horiz_adv_x=advances, kerning_pairs={}, glyphs=built)
    (output_dir / "font.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf8")
